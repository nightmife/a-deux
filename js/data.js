export const BOOST_CAP = { huile: 15, emmental: 40, cacahuetes: 30, beurre: 15 };

function R(id, name, emoji, time, equip, ing, steps, boost = 'huile') {
  return {
    id, name, emoji, time, steps, boost,
    equip: equip.split(' ').map((g) => g.split('|')),
    ing: ing.split(',').map((s) => {
      const [iid, q, role] = s.trim().split(':');
      if (!INGREDIENTS[iid]) throw new Error(`Ingrédient inconnu "${iid}" dans ${id}`);
      return { id: iid, q: Number(q), role: role || INGREDIENTS[iid].role };
    }),
  };
}

